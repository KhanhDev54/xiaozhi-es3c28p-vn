#!/usr/bin/env python3
"""Synthesise the 10 KenDev alarm tones and write alarm_tones.cc.

Every tone is generated here from sine waves and envelopes (no recorded or
third-party audio). Needs numpy and ffmpeg with libopus. Run from this folder:
    python3 make_alarm_tones.py
"""
import os
import subprocess
import tempfile
import wave

import numpy as np

SR = 16000
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "alarm_tones.cc")


def note(f):
    return 440.0 * 2 ** ((f - 69) / 12.0)  # MIDI number -> Hz


def silence(sec):
    return np.zeros(int(SR * sec))


def tone(freq, sec, decay=6.0, harmonics=((1, 1.0),), attack=0.005, sweep=0.0):
    t = np.arange(int(SR * sec)) / SR
    f = freq * (1 + sweep * t / max(sec, 1e-6))
    phase = 2 * np.pi * np.cumsum(f) / SR
    y = sum(a * np.sin(h * phase) for h, a in harmonics)
    env = np.exp(-decay * t)
    a = int(SR * attack)
    if a > 0:
        env[:a] *= np.linspace(0, 1, a)
    return y * env


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def seq(*parts):
    return np.concatenate(parts)


BELL = ((1, 1.0), (2.76, 0.4), (5.4, 0.2))
PLUCK = ((1, 1.0), (2, 0.35), (3, 0.15))
WOOD = ((1, 1.0), (4, 0.25))
PIANO = ((1, 1.0), (2, 0.5), (3, 0.25), (4, 0.1))


def t_bell():  # Chuông nhẹ
    return seq(*[tone(note(n), 0.6, 3.5, BELL) for n in (84, 88, 91)], silence(0.4))


def t_beep():  # Bíp bíp
    b = tone(880, 0.12, 0, ((1, 1.0), (3, 0.2)))
    return seq(b, silence(0.1), b, silence(0.1), b, silence(0.1), b, silence(0.9))


def t_birds():  # Chim sáng
    c = lambda f, s: tone(f, 0.09, 12, sweep=s)
    return seq(c(2600, 0.5), silence(0.05), c(3000, 0.4), silence(0.25), c(2400, 0.6), silence(0.05),
               c(2800, 0.5), silence(0.05), c(3200, 0.3), silence(1.0))


def t_harp():  # Đàn hạc
    return seq(*[tone(note(n), 0.18, 5, PLUCK) for n in (72, 76, 79, 84, 88)], tone(note(91), 0.9, 3, PLUCK))


def t_sunrise():  # Bình minh
    chord = mix(*[tone(note(n), 2.2, 0.8, PLUCK, attack=1.0) for n in (60, 64, 67, 72)])
    return seq(chord, silence(0.2))


def t_clock():  # Đồng hồ cổ
    tick = tone(2000, 0.03, 60, WOOD)
    tock = tone(1500, 0.03, 60, WOOD)
    return seq(tick, silence(0.22), tock, silence(0.22), tick, silence(0.22), tock, silence(0.22),
               tone(note(81), 1.1, 2.5, BELL))


def t_marimba():  # Marimba
    mel = (72, 76, 79, 76, 81, 79)
    return seq(*[tone(note(n), 0.25, 10, WOOD) for n in mel], silence(0.8))


def t_drops():  # Giọt nước
    d = lambda f: tone(f, 0.12, 25, sweep=0.6)
    return seq(d(900), silence(0.15), d(1200), silence(0.3), d(1000), silence(0.1), d(1400), silence(1.1))


def t_piano():  # Piano vui
    mel = ((67, 0.2), (72, 0.2), (76, 0.2), (79, 0.4), (76, 0.2), (79, 0.7))
    return seq(*[tone(note(n), d, 4, PIANO) for n, d in mel], silence(0.3))


def t_urgent():  # Khẩn cấp
    a = tone(1000, 0.1, 0, ((1, 1.0), (3, 0.3)))
    b = tone(1300, 0.1, 0, ((1, 1.0), (3, 0.3)))
    return seq(*([a, b] * 6), silence(0.5))


TONES = [
    ("Chuông nhẹ", t_bell),
    ("Bíp bíp", t_beep),
    ("Chim sáng", t_birds),
    ("Đàn hạc", t_harp),
    ("Bình minh", t_sunrise),
    ("Đồng hồ cổ", t_clock),
    ("Marimba", t_marimba),
    ("Giọt nước", t_drops),
    ("Piano vui", t_piano),
    ("Khẩn cấp", t_urgent),
]


def encode(samples, tmp):
    samples = samples / max(1e-9, np.max(np.abs(samples))) * 0.8
    pcm = (samples * 32767).astype(np.int16)
    wav_path = os.path.join(tmp, "t.wav")
    ogg_path = os.path.join(tmp, "t.ogg")
    with wave.open(wav_path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", wav_path, "-c:a", "libopus", "-b:a", "24k",
                    "-frame_duration", "60", "-application", "audio", "-map_metadata", "-1", ogg_path], check=True)
    return open(ogg_path, "rb").read()


def main():
    out = ["// Generated by tools/make_alarm_tones.py - do not edit.",
           "// Ten alarm tones synthesised from sine waves (no recorded audio), Ogg Opus 16 kHz mono.",
           "", "#include \"alarm_tones.h\"", "", "#include <cstdint>", ""]
    names = []
    with tempfile.TemporaryDirectory() as tmp:
        for i, (name, fn) in enumerate(TONES):
            data = encode(fn(), tmp)
            names.append(name)
            out.append(f"static const uint8_t kTone{i}[] = {{")
            for j in range(0, len(data), 20):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in data[j:j + 20]) + ",")
            out.append("};")
            print(f"{i}: {name} {len(data)} bytes")
    out.append("")
    out.append("struct ToneEntry {\n    const char* name;\n    const uint8_t* data;\n    size_t size;\n};")
    out.append("static const ToneEntry kTones[] = {")
    for i, n in enumerate(names):
        out.append(f"    {{\"{n}\", kTone{i}, sizeof(kTone{i})}},")
    out.append("};")
    out.append("""
int AlarmToneCount() { return sizeof(kTones) / sizeof(kTones[0]); }

const char* AlarmToneName(int index) {
    if (index < 0 || index >= AlarmToneCount()) index = 0;
    return kTones[index].name;
}

std::string_view AlarmToneOgg(int index) {
    if (index < 0 || index >= AlarmToneCount()) index = 0;
    return std::string_view(reinterpret_cast<const char*>(kTones[index].data), kTones[index].size);
}""")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
